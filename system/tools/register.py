#!/usr/bin/env python3
"""Append-only writer for governance/register.

Original texts and compilation versions are immutable. Every transaction is
appended to chain.log; index.yaml is regenerated from that history. Writers
hold an exclusive lock through confirmation and commit.

  sudo /usr/bin/python3 -I /Library/Governance/tools/register.py add --kind S --title 登记法 --asmade FILE [--statement FILE] [--note TEXT]
  register.py amend --target S2026-002 --expected-version 1 --title 修正案 --asmade FILE --statement FILE
Amend accepts only numbered “将《TITLE》（ID vN）第X条修改为：”
paragraphs containing one 「§X ...」 replacement, followed by the numbered
“本修正案未点名的条文继续有效。” clause. Unnamed articles remain byte-identical.
The amendment defaults to no action categories; the target retains its categories.
The target index hash advances to the amendment transaction, while its original
statement stays attached. The amendment has its own statement and amends link.
Confirmation shows frozen source bytes and the resulting compilation together.
Interrupted writes may leave immutable orphan files; subsequent registration
refuses to overwrite them rather than attempting an unconfirmed recovery.
  register.py verify
"""

import argparse
import datetime
import contextlib
import hashlib
import fcntl
import functools
import json
import os
import pwd
import re
import stat
import sys

KINDS = {
    "C": "宪法",
    "S": "成文法",
    "P": "判例法",
    "I": "解释",
    "G": "公报",
}
# Action categories shared with the gate program (S2026-002 §5); "*" covers every category.
CATEGORIES = ("*", "read", "write", "exec", "send", "delegate", "internal", "register")
GENESIS = "0" * 64
DEFAULT_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "register")


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(65536), b""):
            h.update(block)
    return h.hexdigest()


def entry_hash(entry):
    body = {k: v for k, v in entry.items() if k != "hash"}
    canonical = json.dumps(body, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def read_chain(root):
    path = os.path.join(root, "chain.log")
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def next_id(chain, kind, year):
    prefix = "%s%d-" % (kind, year)
    used = [int(e["id"][len(prefix):]) for e in chain if e["id"].startswith(prefix)]
    return "%s%03d" % (prefix, max(used, default=0) + 1)


def q(value):
    # JSON strings are valid YAML scalars.
    return json.dumps(value, ensure_ascii=False)


def current_entries(chain):
    entries = {}
    for event in chain:
        op = event.get("op")
        if op == "attach":
            entries[event["id"]]["files"].update(event["files"])
        elif op == "meta":
            entries[event["id"]]["applies"] = event["applies"]
        else:
            entry = dict(event, files=dict(event["files"]), applies=event.get("applies", []))
            entries[event["id"]] = entry
            if op == "amend":
                change = event["amends"]
                target = entries[change["target"]]
                target.update(version=change["version"], latest=change["latest"],
                              hash=event["hash"])
                target["files"][change["latest"]] = event["files"][change["latest"]]
    return entries


def write_index(root, chain):
    lines = [
        "# generated by governance/tools/register.py from chain.log; never hand-edited",
        "entries:",
    ]
    entries = current_entries(chain)
    for e in entries.values():
        files = e["files"]
        statement = e["id"] + "/statement.md"
        lines += [
            "  - id: %s" % q(e["id"]),
            "    kind: %s" % q(e["kind"]),
            "    kind_name: %s" % q(KINDS[e["kind"]]),
            "    title: %s" % q(e["title"]),
            "    status: %s" % q("有效"),
            "    latest: %s" % q(e["latest"]),
            "    path: %s" % q(e["path"]),
        ]
        if statement in files:
            lines.append("    statement: %s" % q(statement))
        if e.get("op") == "amend":
            lines.append("    amends: %s" % q(e["amends"]["target"]))
        lines += [
            # S2026-001 v1 §10: action categories this entry governs; JSON arrays are YAML flow sequences.
            "    applies: %s" % json.dumps(e["applies"], ensure_ascii=False),
            "    registered_at: %s" % q(e["registered_at"]),
            "    hash: %s" % q(e["hash"]),
        ]
    tmp = os.path.join(root, "index.yaml.tmp")
    with open(tmp, "x", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, os.path.join(root, "index.yaml"))


def verify(root):
    try:
        chain = read_chain(root)
    except (OSError, ValueError) as exc:
        return [], ["cannot read chain: %s" % exc]
    prev = GENESIS
    problems, owners, registered_files = [], {}, set()
    for seq, e in enumerate(chain, 1):
        try:
            if e["seq"] != seq:
                raise ValueError("sequence mismatch")
            if e["prev"] != prev:
                problems.append("%s: prev link broken" % e["id"])
            if entry_hash(e) != e["hash"]:
                problems.append("%s: entry hash mismatch" % e["id"])
            for rel, digest in e["files"].items():
                if (os.path.isabs(rel) or "\\" in rel or
                        any(part in ("", ".", "..") for part in rel.split("/"))):
                    raise ValueError("unsafe registered path")
                path = os.path.join(root, rel)
                if os.path.realpath(path) != os.path.join(os.path.realpath(root), rel):
                    raise ValueError("registered path traverses symlink")
                if rel in registered_files:
                    raise ValueError("registered file appears in multiple transactions")
                registered_files.add(rel)
                if not os.path.isfile(path):
                    problems.append("%s: missing %s" % (e["id"], rel))
                elif sha256_file(path) != digest:
                    problems.append("%s: %s changed" % (e["id"], rel))
            op = e.get("op")
            if op in (None, "amend"):
                if e["id"] in owners:
                    raise ValueError("duplicate registration ID")
                if op == "amend":
                    change = e["amends"]
                    owner = owners[change["target"]]
                    if (owner["kind"] != "S" or e["kind"] != "S" or
                            change["base_version"] != owner["version"] or
                            change["base_latest"] != owner["latest"] or
                            change["version"] != owner["version"] + 1 or
                            change["latest"] != "%s/v%d.md" % (owner["id"], change["version"])):
                        raise ValueError("amendment version linkage mismatch")
                    amendment_path = e["id"] + "/asmade.md"
                    required = {amendment_path, e["id"] + "/v1.md",
                                e["id"] + "/statement.md", change["latest"]}
                    if set(e["files"]) != required or e["latest"] != e["id"] + "/v1.md":
                        raise ValueError("amendment file set mismatch")
                    with open(os.path.join(root, owner["latest"]), "rb") as f:
                        base = f.read()
                    with open(os.path.join(root, amendment_path), "rb") as f:
                        amendment = f.read()
                    compiled, replaced = compile_amendment(
                        base, amendment, owner["id"], owner["version"], owner["title"])
                    if (hashlib.sha256(base).hexdigest() != change["base_hash"] or
                            replaced != change["articles"] or
                            hashlib.sha256(compiled).hexdigest() != e["files"][change["latest"]] or
                            e["files"][amendment_path] != e["files"][e["latest"]]):
                        raise ValueError("amendment compilation mismatch")
                    owner.update(version=change["version"], latest=change["latest"])
                owners[e["id"]] = dict(e)
            elif op not in ("attach", "meta") or e["id"] not in owners:
                raise ValueError("unknown operation or target")
            prev = e["hash"]
        except (KeyError, TypeError, ValueError, OSError) as exc:
            problems.append("entry %d: %s" % (seq, exc))
    return chain, problems


def write_frozen(path, data):
    with open(path, "xb") as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())
    os.chmod(path, 0o444)

def require_sudo():
    user = os.environ.get("SUDO_USER", "")
    try:
        uid = int(os.environ.get("SUDO_UID", "-1"))
        valid = uid > 0 and pwd.getpwnam(user).pw_uid == uid
    except (ValueError, KeyError):
        valid = False
    if os.geteuid() != 0 or not valid:
        sys.exit("refusing to append: run through sudo as the sovereign")


@contextlib.contextmanager
def registry_lock(root):
    os.makedirs(root, exist_ok=True)
    fd = os.open(os.path.join(root, ".register.lock"),
                 os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            sys.exit("invalid registry lock")
        fcntl.flock(fd, fcntl.LOCK_EX)
        yield
    finally:
        os.close(fd)


def serialized(function):
    @functools.wraps(function)
    def locked(root, *args, **kwargs):
        require_sudo()
        with registry_lock(root):
            return function(root, *args, **kwargs)
    return locked



def confirm(sources):
    # Constitution B3 and D5: every append is confirmed by the sovereign's own
    # system password, which sudo demands. Without root the register stays read-only.
    require_sudo()
    # Constitution D4: the sovereign confirms the exact text about to be registered.
    # The bytes shown are the bytes written, so the source cannot change in between.
    if not sys.stdin.isatty() or not sys.stdout.isatty():
        sys.exit("refusing to append: confirmation needs an interactive terminal")
    texts = {}
    for label, src in sources:
        if src:
            if isinstance(src, bytes):
                texts[label] = src
            else:
                with open(src, "rb") as f:
                    texts[label] = f.read()
            print("===== %s sha256=%s =====" % (label, hashlib.sha256(texts[label]).hexdigest()))
            print(texts[label].decode("utf-8"))
    if input("以上为将要登记的文本。输入「确认」登记：").strip() != "确认":
        sys.exit("not confirmed, nothing registered")
    return texts


def consistent_chain(root):
    os.makedirs(root, exist_ok=True)
    chain, problems = verify(root)
    if problems:
        sys.exit("register is inconsistent, refusing to append:\n" + "\n".join(problems))
    return chain


def append(root, chain, entry):
    entry["prev"] = chain[-1]["hash"] if chain else GENESIS
    entry["hash"] = entry_hash(entry)
    with open(os.path.join(root, "chain.log"), "a", encoding="utf-8") as f:
        f.write(json.dumps(entry, ensure_ascii=False, sort_keys=True) + "\n")
        f.flush()
        os.fsync(f.fileno())
    write_index(root, chain + [entry])


def confirmation(note):
    return {"via": "sudo", "user": os.environ["SUDO_USER"], "note": note}


def parse_applies(value):
    cats = [c.strip() for c in (value or "").split(",") if c.strip()]
    unknown = [c for c in cats if c not in CATEGORIES]
    if unknown:
        sys.exit("unknown action categories: %s (known: %s)" % (", ".join(unknown), ", ".join(CATEGORIES)))
    return cats


@serialized
def add(root, kind, title, asmade, statement, note, applies):
    # S2026-001 v1 §5: statutes, precedents and interpretations carry a statement.
    if kind in ("S", "P", "I") and not statement:
        sys.exit("refusing to append: kind %s requires --statement" % kind)
    texts = confirm((("原文", asmade), ("说明书", statement)))
    chain = consistent_chain(root)

    now = datetime.datetime.now().astimezone()
    new_id = next_id(chain, kind, now.year)
    files = {}

    if kind == "G":
        rel = new_id + ".md"
        dest = os.path.join(root, rel)
        if os.path.exists(dest):
            sys.exit("refusing to overwrite " + rel)
        write_frozen(dest, texts["原文"])
        files[rel] = sha256_file(dest)
        path, latest = rel, rel
    else:
        folder = os.path.join(root, new_id)
        if os.path.exists(folder):
            sys.exit("refusing to overwrite " + new_id)
        os.makedirs(folder)
        os.chmod(folder, 0o755)
        plan = [("asmade.md", texts["原文"]), ("v1.md", texts["原文"])]
        if statement:
            plan.append(("statement.md", texts["说明书"]))
        for name, data in plan:
            write_frozen(os.path.join(folder, name), data)
            rel = new_id + "/" + name
            files[rel] = sha256_file(os.path.join(root, rel))
        path, latest = new_id + "/", new_id + "/v1.md"

    entry = {
        "seq": len(chain) + 1,
        "id": new_id,
        "kind": kind,
        "title": title,
        "version": 1,
        "path": path,
        "latest": latest,
        "files": files,
        "registered_at": now.isoformat(timespec="seconds"),
        "confirmation": confirmation(note),
        "applies": applies,
    }
    append(root, chain, entry)
    print(new_id)


@serialized
def attach(root, target, statement, note):
    # S2026-001 v1 §4: a statement missing from an entry folder is added, never replaced.
    texts = confirm((("说明书", statement),))
    chain = consistent_chain(root)
    owner = [e for e in chain if e["id"] == target and e.get("op") in (None, "amend")]
    if not owner or owner[0]["kind"] == "G":
        sys.exit("refusing to attach: %s is not a registered law entry" % target)
    rel = target + "/statement.md"
    dest = os.path.join(root, rel)
    if os.path.exists(dest):
        sys.exit("refusing to overwrite " + rel)
    write_frozen(dest, texts["说明书"])
    entry = {
        "seq": len(chain) + 1,
        "op": "attach",
        "id": target,
        "files": {rel: sha256_file(dest)},
        "registered_at": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
        "confirmation": confirmation(note),
    }
    append(root, chain, entry)
    print(rel)


@serialized
def meta(root, target, applies, note):
    # S2026-001 v1 §10: action categories recorded for an existing entry, appended to the chain.
    summary = ("%s 适用的动作类别：%s\n" % (target, json.dumps(applies, ensure_ascii=False))).encode("utf-8")
    confirm((("索引事项", summary),))
    chain = consistent_chain(root)
    if target not in current_entries(chain):
        sys.exit("refusing to record categories: %s is not a registered entry" % target)
    entry = {
        "seq": len(chain) + 1,
        "op": "meta",
        "id": target,
        "applies": applies,
        "files": {},
        "registered_at": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
        "confirmation": confirmation(note),
    }
    append(root, chain, entry)
    print("%s applies %s" % (target, ",".join(applies)))


def articles(data):
    text = data.decode("utf-8")
    starts = list(re.finditer(r"^§([1-9][0-9]*)[ \t]+", text, re.MULTILINE))
    if not starts:
        raise ValueError("base has no numbered articles")
    parts = {}
    for index, match in enumerate(starts):
        number = int(match.group(1))
        if number in parts:
            raise ValueError("duplicate article %d" % number)
        end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
        parts[number] = text[match.start():end]
    return text[:starts[0].start()], parts


def chinese_number(number):
    if not 1 <= number <= 9999:
        raise ValueError("article number must be between 1 and 9999")
    digits = "零一二三四五六七八九"
    result, zero = "", False
    for divisor, unit in ((1000, "千"), (100, "百"), (10, "十"), (1, "")):
        digit, number = divmod(number, divisor)
        if digit:
            if zero:
                result += "零"
            result += digits[digit] + unit
            zero = False
        elif result and number:
            zero = True
    return result[1:] if result.startswith("一十") else result


def compile_amendment(base, amendment, target, version, title):
    """Parse the narrow legislative form; never execute amendment content."""
    prefix, original = articles(base)
    text = amendment.decode("utf-8")
    heading = re.match(r"#[^\n]+\n+", text)
    if not heading:
        raise ValueError("amendment needs a title and numbered replacement paragraphs")
    position = heading.end()
    replacements = {}
    sequence = 1
    pattern = re.compile(
        r"§([1-9][0-9]*) 将《([^》\n]+)》（([A-Z][0-9]{4}-[0-9]{3,}) v([1-9][0-9]*)）"
        r"第([^条\n]+)条修改为：\n\n「(§([1-9][0-9]*) [\s\S]*?)」(?:\n\n|\n?$)")
    while True:
        match = pattern.match(text, position)
        if not match:
            break
        seq, named_title, named_target, named_version, ordinal, replacement, number = match.groups()
        number = int(number)
        if int(seq) != sequence:
            raise ValueError("amendment paragraphs must be consecutive")
        if (named_target, int(named_version), named_title) != (target, version, title):
            raise ValueError("amendment target, base version or title does not match")
        if ordinal not in (chinese_number(number), str(number)):
            raise ValueError("named article differs from replacement article")
        if number not in original:
            raise ValueError("unknown target article %d" % number)
        if number in replacements:
            raise ValueError("duplicate target article %d" % number)
        _, nested = articles(replacement.encode("utf-8"))
        if list(nested) != [number]:
            raise ValueError("replacement must contain exactly the named article")
        suffix = original[number][len(original[number].rstrip("\n")):]
        replacements[number] = replacement + suffix
        position = match.end()
        sequence += 1
    closing = "§%d 本修正案未点名的条文继续有效。" % sequence
    if not replacements or text[position:].rstrip("\n") != closing:
        raise ValueError("missing replacement or unsupported amendment paragraph")
    result = (prefix + "".join(replacements.get(n, body) for n, body in original.items())).encode("utf-8")
    new_prefix, compiled = articles(result)
    if new_prefix != prefix or list(compiled) != list(original):
        raise ValueError("compilation changed article structure")
    if any(compiled[n] != body for n, body in original.items() if n not in replacements):
        raise ValueError("compilation changed an unnamed article")
    return result, list(replacements)


@serialized
def amend(root, target, expected_version, title, asmade, statement, note, applies):
    chain = consistent_chain(root)
    owner = current_entries(chain).get(target)
    if not owner or owner["kind"] != "S":
        sys.exit("refusing to amend: target must be a registered statute")
    if owner["version"] != expected_version:
        sys.exit("refusing to amend: expected v%d, current is v%d" %
                 (expected_version, owner["version"]))
    with open(os.path.join(root, owner["latest"]), "rb") as f:
        base = f.read()
    with open(asmade, "rb") as f:
        amendment = f.read()
    with open(statement, "rb") as f:
        explanation = f.read()
    if not explanation.strip():
        sys.exit("refusing to amend: explanatory statement is empty")
    try:
        compilation, replaced = compile_amendment(
            base, amendment, target, expected_version, owner["title"])
    except (ValueError, UnicodeError) as exc:
        sys.exit("refusing to amend: %s" % exc)
    now = datetime.datetime.now().astimezone()
    new_id = next_id(chain, "S", now.year)
    version = expected_version + 1
    latest = "%s/v%d.md" % (target, version)
    plan = [
        (new_id + "/asmade.md", amendment),
        (new_id + "/v1.md", amendment),
        (new_id + "/statement.md", explanation),
        (latest, compilation),
    ]
    folder = os.path.join(root, new_id)
    if os.path.lexists(folder):
        sys.exit("refusing to overwrite " + new_id)
    for rel, _ in plan:
        if os.path.lexists(os.path.join(root, rel)):
            sys.exit("refusing to overwrite " + rel)
    summary = ("%s: %s v%d → v%d; articles %s; title %s; applies %s\n" %
               (new_id, target, expected_version, version, replaced, title, applies)).encode("utf-8")
    confirm((("登记事项", summary), ("修正案原文", amendment), ("说明书", explanation),
             ("汇编 " + latest, compilation)))
    os.mkdir(folder, 0o755)
    files = {}
    for rel, data in plan:
        write_frozen(os.path.join(root, rel), data)
        files[rel] = hashlib.sha256(data).hexdigest()
    entry = {
        "seq": len(chain) + 1, "op": "amend", "id": new_id, "kind": "S",
        "title": title, "version": 1, "path": new_id + "/", "latest": new_id + "/v1.md",
        "files": files, "registered_at": now.isoformat(timespec="seconds"),
        "confirmation": confirmation(note), "applies": applies,
        "amends": {"target": target, "base_version": expected_version,
                   "base_latest": owner["latest"], "base_hash": hashlib.sha256(base).hexdigest(),
                   "version": version, "latest": latest, "articles": replaced},
    }
    append(root, chain, entry)
    print("%s; %s" % (new_id, latest))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=DEFAULT_ROOT)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_add = sub.add_parser("add")
    p_add.add_argument("--kind", required=True, choices=sorted(KINDS))
    p_add.add_argument("--title", required=True)
    p_add.add_argument("--asmade", required=True)
    p_add.add_argument("--statement")
    p_add.add_argument("--note", default="")
    p_add.add_argument("--applies", default="", help="comma-separated action categories")

    p_amend = sub.add_parser("amend", help="register a constrained amendment and compile its target")
    p_amend.add_argument("--target", required=True)
    p_amend.add_argument("--expected-version", required=True, type=int)
    p_amend.add_argument("--title", required=True)
    p_amend.add_argument("--asmade", required=True)
    p_amend.add_argument("--statement", required=True)
    p_amend.add_argument("--note", default="")
    p_amend.add_argument("--applies", default="", help="comma-separated action categories")

    p_meta = sub.add_parser("meta")
    p_meta.add_argument("--target", required=True)
    p_meta.add_argument("--applies", required=True)
    p_meta.add_argument("--note", default="")

    p_attach = sub.add_parser("attach")
    p_attach.add_argument("--target", required=True)
    p_attach.add_argument("--statement", required=True)
    p_attach.add_argument("--note", default="")

    sub.add_parser("verify")

    args = parser.parse_args()
    root = os.path.abspath(args.root)
    if args.cmd == "add":
        add(root, args.kind, args.title, args.asmade, args.statement, args.note, parse_applies(args.applies))
    elif args.cmd == "amend":
        amend(root, args.target, args.expected_version, args.title, args.asmade,
              args.statement, args.note, parse_applies(args.applies))
    elif args.cmd == "attach":
        attach(root, args.target, args.statement, args.note)
    elif args.cmd == "meta":
        meta(root, args.target, parse_applies(args.applies), args.note)
    else:
        chain, problems = verify(root)
        if problems:
            print("\n".join(problems))
            sys.exit(1)
        print("ok: %d entries" % len(chain))


if __name__ == "__main__":
    main()
